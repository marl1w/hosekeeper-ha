const LANGS = { en, it };

export function pickLanguage(hass) {
  const raw = (hass && (hass.locale?.language || hass.language)) || "en";
  return raw.toLowerCase().startsWith("it") ? "it" : "en";
}

export function strings(lang) {
  return LANGS[lang] || en;
}

/** Look up a code in a table, falling back to English, then to the code itself. */
export function lookup(lang, table, code) {
  const s = strings(lang);
  return (s[table] && s[table][code]) || (en[table] && en[table][code]) || code;
}
